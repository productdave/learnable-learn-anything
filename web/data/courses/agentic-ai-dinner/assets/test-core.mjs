import assert from 'node:assert/strict';
import {MENU,total,searchMenu,createState,draftCart,approveCart,changeQuote,submitSimulation,evaluate} from './builder-core.mjs';
assert.equal(total(MENU[0]),2100);
assert.equal(total(MENU[0],2,200),3900);
for(const n of [0,-1,1.5,11])assert.throws(()=>total(MENU[0],n));
assert.throws(()=>total(MENU.find(x=>x.id==='unknown-fees')));
assert.throws(()=>searchMenu({budgetCents:0}));
assert(searchMenu({budgetCents:2100}).candidates.every(x=>x.total<2100));
assert(searchMenu({query:'tofu',staleTofu:true}).excluded.some(x=>x.id==='tofu-bowl'&&x.reasons.includes('Stale source')));
assert(searchMenu({query:'anything',tipCents:1000}).candidates.length===0);
const s=createState();
assert.throws(()=>submitSimulation(s));
assert.throws(()=>draftCart(s,{itemId:'chicken-bowl',vegetarian:true}));
assert.throws(()=>draftCart(s,{itemId:'sold-out'}));
draftCart(s,{budgetCents:5000,tipCents:200});assert.equal(s.cart.total,2300);
assert.throws(()=>submitSimulation(s));approveCart(s);
draftCart(s,{quantity:2});assert.equal(s.approvedVersion,null);assert.throws(()=>submitSimulation(s));
approveCart(s);changeQuote(s,200);assert.equal(s.approvedVersion,null);assert.throws(()=>submitSimulation(s));
approveCart(s);assert.throws(()=>submitSimulation(s,{timeout:true}));
const receipt=submitSimulation(s);assert.equal(receipt.id,submitSimulation(s).id);assert.equal(s.receipts.length,1);
assert(evaluate().releaseGate);assert(!evaluate('omit-fees').releaseGate);assert(!evaluate('skip-approval').releaseGate);
console.log('Core checks passed: filtering, strict budgets, totals, state, approvals, and uncertain retry deduplication.');
