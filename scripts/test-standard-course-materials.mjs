import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { parseHTML } from 'linkedom';
import { creationBrief, creationComponents, componentPolicy, retainComponentChoices } from '../web/js/generator/component-policy.mjs';
import { draftContent } from '../web/js/draft-store.js';
import { setupDraft } from '../web/js/setup-model.js';
import { experienceHTML } from '../web/js/course-setup.js';
import { componentSummaryHTML, componentSetupIssues } from '../web/js/setup-components.js';
import { canonicalMaterials, readMaterialDefaults } from '../web/js/material-defaults.js';
import { normalizeAccountPayload, prepareAccountPayload } from '../web/js/setup-account-model.js';
import { setupGenerationIssues, setupToGenerationBrief } from '../web/api/_lib/setup-generation.mjs';
import { topicToolFor } from '../web/js/generator/stages/topic.mjs';
import { topicContentSchemaFor } from '../web/js/generator/schema.mjs';
import { curriculumFixture, lessonFixture } from './fixtures/component-course.mjs';
import { assembleCourse } from '../web/js/generator/assemble-course.js';
import { inspectSavedCourse } from '../web/js/course-readiness.js';

let checks = 0;
const check = (value, label) => { assert.ok(value, label); checks++; };
const equal = (actual, expected, label) => { assert.deepEqual(actual, expected, label); checks++; };
for (let bits = 0; bits < 8; bits++) {
  const optional = ['checklists', 'quizzes', 'flashcards'].filter((_, i) => bits & (1 << i));
  const input = ['lessons', 'practice', ...optional];
  const expected = ['lessons', ...optional, 'images'];
  equal(creationComponents(input), expected, 'every optional combination has images, never Practice');
  equal(draftContent({ components: input }).components, expected, 'resumed setup follows current materials');
  equal(canonicalMaterials(input), expected, 'old defaults adapt without reintroducing Practice');
  const requested = creationBrief({ components: input });
  const planned = retainComponentChoices({ ...curriculumFixture(), components: ['lessons', 'practice'] }, requested);
  equal(planned.components, expected, 'model cannot remove images or restore Practice');
  check(!componentPolicy(planned).practice, 'writer policy excludes Practice');
  const tool = JSON.stringify(topicToolFor(planned));
  check(!tool.includes('"practice"'), 'new-course tool schema excludes Practice sections');
  const topic = planned.modules[0].topics[0];
  const lesson = lessonFixture(expected, topic);
  check(topicContentSchemaFor(planned, topic).safeParse(lesson).success, 'text stage accepts current selected materials');
  lesson.sections.push({ type: 'practice', title: 'Unrequested task' });
  check(!topicContentSchemaFor(planned, topic).safeParse(lesson).success, 'model Practice output is rejected');
}
const draft = setupDraft('Recursive self-improvement for product managers');
draft.brief.audience = 'Beginner product managers';
draft.sources.notes = [{ id: 'n1', title: 'Context', text: 'Keep this exact note.' }];
equal(draft.components, ['lessons', 'quizzes', 'flashcards', 'images'], 'new default includes images');
const { document } = parseHTML(experienceHTML(draft));
check(!document.querySelector('[data-component="practice"]'), 'no Practice checkbox');
check(!document.querySelector('[data-component="images"]'), 'images have no opt-out checkbox');
check(document.querySelectorAll('[data-component]').length === 3, 'only three optional learning tools');
check(document.querySelector('#setup-included-title')?.textContent === 'Included in every course', 'included-content heading');
check(!/Coming later|without them|Optional · Each image/.test(document.toString()), 'no stale unavailable/optional image copy');
check(document.toString().includes('OpenAI usage and cost'), 'cost implications available in the information disclosure');
check(!componentSummaryHTML(['lessons', 'practice']).includes('Practice activities'), 'review excludes retired material');
check(componentSummaryHTML(['lessons']).includes('Generate Course Images'), 'old setup summary includes required images');
check(!componentSetupIssues(draft.components).length, 'server configuration does not block editing setup');
const oldDefaults = { _courseMaterialDefaults: { version: 1, revision: 'legacy', components: ['lessons', 'practice'] } };
const originalDefaults = structuredClone(oldDefaults);
equal(readMaterialDefaults(oldDefaults).components, ['lessons', 'images'], 'reading old preferences adapts only future choices');
equal(oldDefaults, originalDefaults, 'stored preferences not mutated by read');
const prepared = await prepareAccountPayload(draft);
const oldPayload = { ...prepared.payload, components: ['lessons', 'practice'] };
const original = structuredClone(oldPayload);
equal(normalizeAccountPayload(oldPayload).components, ['lessons', 'practice'], 'stored payload canonicalization/hash semantics unchanged');
check(setupGenerationIssues(oldPayload, { imagesEnabled: false }).some(i => i.step === 'create'), 'stale no-image request cannot bypass server image gate');
check(!JSON.stringify(setupGenerationIssues(oldPayload, { imagesEnabled: false })).includes('Uncheck'), 'no opt-out offered as recovery');
const flags = ['LEARNABLE_CREATION_IMAGES', 'LEARNABLE_GPT_IMAGES', 'LEARNABLE_IMAGE_REQUESTS'];
const before = flags.map(key => process.env[key]);
try {
  for (const key of flags) process.env[key] = '1';
  const brief = await setupToGenerationBrief({ id: 'setup-old', revision: 7, content_hash: 'old-hash', payload: oldPayload }, 'owner', {});
  equal(brief.components, ['lessons', 'images'], 'server upgrades stale client for new generation');
  check(!componentPolicy(brief).practice, 'server brief disallows Practice');
  check(brief.source_text.includes('Keep this exact note.') && brief.setup_reference.hash === 'old-hash', 'context and provenance preserved');
} finally { flags.forEach((key, i) => { if (before[i] == null) delete process.env[key]; else process.env[key] = before[i]; }); }
equal(oldPayload, original, 'server translation does not mutate saved input');
const brief = retainComponentChoices(curriculumFixture(), creationBrief({ components: ['lessons'] }));
const course = assembleCourse(brief, brief.modules[0].topics.map(topic => ({ moduleId: 'foundations', topicId: topic.id, content: lessonFixture(['lessons'], topic) })));
check(inspectSavedCourse(course).imageProgress.omitted === 3 && inspectSavedCourse(course).needsAttention, 'new drafts need the learner-facing refinement before ready, even with no illustrations');
course._visualDesign = { version: 1, policy: 'learner-experience-v1', status: 'complete', review: { summary: 'Reviewed' }, items: Object.fromEntries(brief.modules[0].topics.map(topic => [`foundations/${topic.id}`, { status: 'saved' }])), pending: null };
check(!inspectSavedCourse(course).needsAttention, 'completed refinement and explicit omit decisions do not require unnecessary images');
delete course.modules[1]['lesson-1'].visual;
check(inspectSavedCourse(course).imageProgress.unplanned === 1 && inspectSavedCourse(course).needsAttention, 'missing visual decision cannot masquerade as intentional text-only teaching');
check(componentPolicy({ components: ['lessons', 'practice'] }).practice, 'legacy saved-course reader remains compatible');
check(readFileSync('web/api/gen/start.js', 'utf8').includes('creationBrief(inputBrief)'), 'legacy creation endpoint uses current policy too');
check(readFileSync('web/js/setup-create.js', 'utf8').includes('not a problem with your API key'), 'disabled-server explanation distinguishes configuration from credentials');
check(readFileSync('web/js/course-setup.js', 'utf8').includes("step === 'experience' ? 'afterend' : 'beforeend'"), 'saved preferences follow the optional choices they control');
console.log(`Standard course materials: ${checks} checks passed. No provider calls.`);
