import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { createSetupGenerationClient } from '../web/js/setup-generation-client.js';
let request;
const client=createSetupGenerationClient({getIdentity:()=>({id:'owner'}),getClient:async()=>({auth:{getSession:async()=>({data:{session:{user:{id:'owner'},access_token:'synthetic'}}})}}),fetcher:async(url,init)=>{request={url,...init};return {ok:true,json:async()=>({cleared:['waiting-job'],started:[]})};}});
assert.equal(typeof client.refreshCredentials,'function','secure connection needs a clear-only credential recovery path');
assert.deepEqual(await client.refreshCredentials('owner'),{cleared:['waiting-job'],started:[]});
assert.equal(request.url,'/api/gen/credentials-ready'); assert.equal(request.method,'POST');
assert.deepEqual(JSON.parse(request.body),{},'never pass jobId: server treats that as paid resume consent');
const app=readFileSync('web/js/app.js','utf8'),body=app.match(/function refreshWorkspaceCredentialWaits\(event\) \{[\s\S]*?\n\}/)?.[0];
assert.ok(body,'workspace connection events refresh waiting job cards');
let clears=[],refreshes=0;
const run=vm.runInNewContext(`(${body})`,{getUser:()=>({id:'owner'}),clearApiKeyWaitForCloudJobs:(id,list)=>clears.push({id,list}),refreshCloudGenerationState:()=>{refreshes++;return Promise.resolve();}});
run({detail:{owner:'other',connected:true,cleared:['waiting-job']}}); assert.equal(clears.length,0);
run({detail:{owner:'owner',connected:false,cleared:['waiting-job']}}); assert.equal(clears.length,0);
run({detail:{owner:'owner',connected:true}}); assert.equal(clears.length,0);
run({detail:{owner:'owner',connected:true,cleared:['waiting-job']}}); assert.equal(clears.length,1);assert.equal(refreshes,1);
assert.equal(clears[0].id,'');assert.deepEqual(clears[0].list,['waiting-job']);
assert.ok(!/continueCloudJobAfterApiKeySaved|resumeCloudGeneration|restartOrStart/.test(body),'UI refresh cannot start paid recovery');
const ui=readFileSync('web/js/workspace-account.js','utf8');assert.ok(ui.includes('client.refreshCredentials(owner)')&&ui.includes('recoveryPending'),'failed clear-only recovery remains retryable');
console.log('Workspace credential-recovery contracts passed; no auto-resume or provider calls.');
